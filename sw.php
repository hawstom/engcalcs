 * second one; combined with skipWaiting()/clients.claim() below, returning visitors migrate
 * without doing anything.
 *
 * Serving it through PHP rather than rewriting /engcalcs/sw.js to it keeps the change independent
 * of mod_rewrite being available on this shared host -- .htaccess here already carries a warning
 * about an Options directive that 500s the whole suite where the grant is missing, and a service
 * worker is not the place to take that bet.
 *
 * Everything about WHAT is cached, and why, lives in lib/ServiceWorker.lib.php. This file is the
 * behaviour only. It deliberately does NOT load lib/base.inc.php: the worker needs no language,
 * no units and no session, and ecSessionStart()'s consent rules mean a needless bootstrap here
 * would be the worst place to touch storage.
