require_once(__DIR__ . '/lib/ServiceWorker.lib.php');
$ecSwManifest = ecServiceWorkerManifest(__DIR__);
header('Content-Type: application/javascript; charset=utf-8');
// Browsers cap service-worker script caching at 24h anyway; say it explicitly so an intermediary
// cannot pin a stale manifest and freeze the precache list.
header('Cache-Control: no-cache');
$ecSwJson = function ($list) {
    return json_encode($list, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
};
?>
// EngCalcs Service Worker -- GENERATED BY sw.php. Do not edit a copy of this text; edit sw.php
// and lib/ServiceWorker.lib.php.
//
// There is no CACHE_VERSION and there must never be one again (Task 318). Every asset URL below
// carries its file's own mtime, so the cache key moves when the file moves; a hand-bumped version
// string was the banned hardcoded ?v=N living in the one file where forgetting to bump it is
// invisible. Stale and departed entries are pruned in 'activate' instead.
const ASSET_CACHE = 'engcalcs-assets';
const PAGE_CACHE  = 'engcalcs-pages';

// Static assets: cache-first. Generated with the same filemtime() the pages use, which is the
// whole fix -- these strings are byte-identical to the <script src>/<link href> URLs a page
// requests, and dev/scripts/sw_manifest_check.php renders real pages to prove it.
const STATIC_ASSETS = <?=$ecSwJson($ecSwManifest['assets'])?>;

// Calculator pages: network-first, fall back to cache.
const CALC_PAGES = <?=$ecSwJson($ecSwManifest['pages'])?>;

// Install: pre-cache everything.
//
// Deliberately NOT cache.addAll(): addAll is atomic, so one 404 -- a page renamed, an asset
// pruned by a deploy that half-landed -- rejects the whole install and the visitor silently gets
// no offline suite at all. Per-URL with allSettled degrades instead: whatever fetched is offline.
// 'reload' bypasses the HTTP cache so the precache cannot be seeded from a stale intermediary.
self.addEventListener('install', event => {
  event.waitUntil(
    Promise.all([
      precache(ASSET_CACHE, STATIC_ASSETS),
      precache(PAGE_CACHE, CALC_PAGES),
    ]).then(() => self.skipWaiting())
  );
});

async function precache(cacheName, urls) {
  const cache = await caches.open(cacheName);
  await Promise.allSettled(urls.map(url => cache.add(new Request(url, { cache: 'reload' }))));
}

// Activate: drop caches from older schemes, then prune entries this build has superseded.
//
// Pruning is what replaces CACHE_VERSION. Three kinds of entry are deleted:
//   - anything cross-origin (Task 287's case: Bootstrap moved from jsDelivr to this origin, and
//     without this a returning visitor keeps serving the third party we removed);
//   - a same-path entry with a different query, i.e. the previous filemtime of a file we just
//     shipped a new version of -- otherwise every deploy leaves its predecessor behind forever;
//   - nothing else. An asset that is runtime-cached but not precached (epanet-js.js) has no
//     manifest path to collide with, so it survives, which is what we want.
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(k => k.startsWith('engcalcs-') && k !== ASSET_CACHE && k !== PAGE_CACHE)
            .map(k => caches.delete(k))
      ))
      .then(pruneAssets)
      .then(() => self.clients.claim())
  );
});

async function pruneAssets() {
  const cache = await caches.open(ASSET_CACHE);
  const fresh = new Set(STATIC_ASSETS.map(u => new URL(u, self.location).href));
  const freshPaths = new Set(STATIC_ASSETS.map(u => new URL(u, self.location).pathname));
  const requests = await cache.keys();
  await Promise.all(requests.map(request => {
    const url = new URL(request.url);
    if (fresh.has(url.href)) return null;
    if (url.origin !== self.location.origin) return cache.delete(request);
    if (freshPaths.has(url.pathname)) return cache.delete(request);
    return null;
  }));
}

// Fetch: route by request type
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);

  // Only handle GET requests
  if (event.request.method !== 'GET') return;

  // Static assets → cache-first
  if (isStaticAsset(url)) {
    event.respondWith(cacheFirst(event.request, ASSET_CACHE));
    return;
  }

  // EngCalcs pages → network-first
  if (url.pathname.startsWith('/engcalcs/')) {
    event.respondWith(networkFirst(event.request, PAGE_CACHE));
    return;
  }
});

function isStaticAsset(url) {
  return (
    url.pathname.match(/\.(js|css|svg|png|gif|jpg|ico|woff2?)(\?|$)/)
  );
}

async function cacheFirst(request, cacheName) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(cacheName);
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    // Offline AND the exact ?v= is not cached -- which now means the file changed on the server
    // since this browser last cached it, because a matching version is precached. Serving the
    // older copy is strictly better than the alternative, which is a broken page: a calculator
    // that is one deploy behind still computes. This fallback runs ONLY after the network has
    // failed, so it can never shadow a fresh file while online; that ordering is why we did not
    // simply pass {ignoreSearch: true} to the lookup above, which would have defeated cache
    // busting permanently.
    const stale = await caches.match(request, { ignoreSearch: true });
    if (stale) return stale;
    return new Response('Offline — asset not cached', { status: 503 });
  }
}

async function networkFirst(request, cacheName) {
  try {
    const response = await fetch(request);
    if (response.ok) {
      // Strip query params (lang=xx, units=xx) before caching the base page
      const cacheKey = stripQueryParams(request);
      const cache = await caches.open(cacheName);
      cache.put(cacheKey, response.clone());
    }
    return response;
  } catch {
    // Offline: try exact URL, then URL without query params
    const cached =
      (await caches.match(request)) ||
      (await caches.match(stripQueryParams(request)));
    if (cached) return cached;
    return new Response(
      '<!DOCTYPE html><html><head><meta charset="utf-8"><title>Offline</title></head>' +
      '<body><h1>You are offline</h1><p>This page has not been cached yet. ' +
      'Please visit it while connected to the internet first.</p></body></html>',
      { status: 503, headers: { 'Content-Type': 'text/html' } }
    );
  }
}

function stripQueryParams(request) {
  const url = new URL(request.url);
  url.search = '';
  return new Request(url.toString(), { method: request.method, headers: request.headers });
}

// Task 119: Background Sync flush for the offline usage-log queue. Calculators.lib.js
// (main thread) queues failed/offline log-*.php POSTs into IndexedDB and registers this
// tag; the browser fires 'sync' here once connectivity returns, even if no EngCalcs page
// is open. Where Background Sync isn't supported (e.g. Safari), the queue still flushes
// on the next page load / 'online' event via Calculators.lib.js's own flushQueue().
// Keep this DB/store name and record shape in sync with Calculators.lib.js -- it's
// duplicated rather than shared because a service worker can't import page-context JS.
const QUEUE_DB = 'engcalcs-offline-queue';
const QUEUE_STORE = 'queue';
const QUEUE_MAX_ATTEMPTS = 20;

self.addEventListener('sync', event => {
  if (event.tag === 'engcalcs-flush-queue') {
    event.waitUntil(flushOfflineQueue());
  }
});

function openQueueDB() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(QUEUE_DB, 1);
    req.onupgradeneeded = () => {
      req.result.createObjectStore(QUEUE_STORE, { keyPath: 'id', autoIncrement: true });
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

// Reads every queued record into a plain array in its own short-lived transaction.
// IndexedDB transactions auto-commit once there's no pending request in the
// microtask queue, so awaiting fetch() inside a cursor loop would let the
// transaction die before a later cursor.update()/delete() call -- read everything
// first, then do the async network work with separate write transactions.
function readQueue(db) {
  return new Promise((resolve, reject) => {
    const tx = db.transaction(QUEUE_STORE, 'readonly');
    const records = [];
    tx.objectStore(QUEUE_STORE).openCursor().onsuccess = event => {
      const cursor = event.target.result;
      if (!cursor) { resolve(records); return; }
      records.push(cursor.value);
      cursor.continue();
    };
    tx.onerror = () => reject(tx.error);
  });
}

function deleteQueueRecord(db, id) {
  db.transaction(QUEUE_STORE, 'readwrite').objectStore(QUEUE_STORE).delete(id);
}

function updateQueueRecord(db, record) {
  db.transaction(QUEUE_STORE, 'readwrite').objectStore(QUEUE_STORE).put(record);
}

async function flushOfflineQueue() {
  let db;
  try {
    db = await openQueueDB();
  } catch {
    return;
  }
  const records = await readQueue(db);
  await Promise.all(records.map(async record => {
    try {
      const params = Object.assign({}, record.params, { offline_ts: record.offline_ts });
      const resp = await fetch(record.url, {
        method: 'POST',
        body: new URLSearchParams(params),
        credentials: 'same-origin'
      });
      if (resp.ok || record.attempts + 1 >= QUEUE_MAX_ATTEMPTS) {
        deleteQueueRecord(db, record.id);
      } else {
        updateQueueRecord(db, Object.assign({}, record, { attempts: record.attempts + 1 }));
      }
    } catch {
      // Still offline; leave the record queued for the next sync/flush.
    }
  }));
}
