'use strict';

const fs = require('fs');
const path = require('path');

function lines(file) { return fs.existsSync(file) ? fs.readFileSync(file, 'utf8').split('\n').filter(Boolean).map(JSON.parse) : []; }
function median(a) { if (!a.length) { return null; } const s = a.slice().sort(function (x, y) { return x - y; }); const m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; }
function f(v, d) { return v === null || v === undefined || !isFinite(v) ? '-' : (+v).toFixed(d === undefined ? 1 : d); }
function table(head, rows) { return '| ' + head.join(' | ') + ' |\n|' + head.map(function () { return '---'; }).join('|') + '|\n' + rows.map(function (r) { return '| ' + r.join(' | ') + ' |'; }).join('\n') + '\n'; }

const work = process.argv[2];
const views = {};
function add(name, arr) { views[name] = arr; }
['PROD', 'MAST'].forEach(function (p) { add(p, lines(path.join(work, 'raw', p + '.jsonl'))); });
['A7', 'B7', 'C7', 'D7'].forEach(function (p) {
	add(p, lines(path.join(__dirname, '../round-7/raw', p + '.jsonl')).filter(function (v) { return v.exp === 'E1'; }));
	add(p + '@mast', lines(path.join(work, 'raw', p + '-mast.jsonl')));
});

function pooled(vs) {
	const s = function (k) { return vs.reduce(function (t, v) { return t + (v[k] || 0); }, 0); };
	const ms = vs.map(function (v) { return v.ms; });
	const sets = {};
	vs.forEach(function (v) { sets[v.set] = 1; });
	const shown = s('labelsShown');
	return {
		sets: Object.keys(sets).length, views: vs.length,
		labels: 100 * shown / s('labelsReq'), values: 100 * s('valuesShown') / s('valuesReq'),
		N1: s('N1'), N3: s('N3'), N1per100: 100 * s('N1') / shown, N3per100: 100 * s('N3') / shown,
		ldl: 100 * s('leaderOnLeader') / shown, lol: 100 * s('labelOnLeader') / shown, ldp: 100 * s('leaderOnLink') / shown, lop: 100 * s('labelOnLink') / shown,
		tom: s('costTom') / shown, along: s('r14asked') ? 100 * s('r14along') / s('r14asked') : null,
		held: s('hidden') ? 100 * s('heldRoom') / s('hidden') : null,
		msMed: median(ms), msMax: ms.length ? Math.max.apply(null, ms) : null, over1s: ms.filter(function (x) { return x > 1000; }).length,
		shown: shown
	};
}
function perSet(vs) {
	const by = {};
	vs.forEach(function (v) { const b = by[v.set] = by[v.set] || { req: 0, shown: 0, vreq: 0, vshown: 0 }; b.req += v.labelsReq; b.shown += v.labelsShown; b.vreq += v.valuesReq; b.vshown += v.valuesShown; });
	return by;
}
function wins(a, b) {
	const A = perSet(views[a]), B = perSet(views[b]);
	let w = 0, l = 0, n = 0;
	Object.keys(A).forEach(function (k) { if (!B[k]) { return; } n++; const d = A[k].shown / A[k].req - B[k].shown / B[k].req; if (d > 0) { w++; } else if (d < 0) { l++; } });
	return w + ' of ' + n + (l ? ' (' + l + ' fewer)' : '');
}

const out = [];
out.push('# Placement vs production: results (generated by analyse.js; do not edit by hand)\n');
out.push('E1: 64 secret sets of round 7 (1,000 nodes; grid, tree, suburban, downtown; seeds 71-74; plain and bent-and-valved; 28 and 44 px), five zooms each.\n');
const order = ['PROD', 'MAST', 'A7', 'B7', 'C7', 'D7', 'A7@mast', 'B7@mast', 'C7@mast', 'D7@mast'];
const rows = [];
order.forEach(function (p) {
	if (!views[p] || !views[p].length) { return; }
	const P = pooled(views[p]);
	rows.push([p, P.sets, f(P.labels), f(P.values), P.N1 + ' (' + f(P.N1per100, 2) + ')', P.N3 + ' (' + f(P.N3per100, 2) + ')', f(P.ldl, 2), f(P.lol, 2), f(P.ldp, 1), f(P.lop, 1), f(P.tom, 3), f(P.along, 0), f(P.held), f(P.msMed, 0) + ' / ' + f(P.msMax, 0), P.over1s + '/' + P.views]);
});
out.push('\n## E1, pooled\n');
out.push(table(['entrant', 'sets', 'labels %', 'values %', 'N1 overlaps (per 100 shown)', 'N3 leader through node (per 100)', 'leader on leader /100', 'label on leader /100', 'leader on pipe /100', 'label on pipe /100', 'Tom cost /label', 'along %', 'hidden with room, held-back %', 'ms median / max', 'views > 1 s'], rows));
out.push('\nPROD and MAST times are the page\'s whole refreshLabelText() pass on the node DOM stub (label text and layout, over the whole network), not place() alone.\n');
out.push('\n## Paired, labels shown per set\n');
out.push(table(['comparison', 'more labels on'], [['A7 vs PROD', wins('A7', 'PROD')], ['B7 vs PROD', wins('B7', 'PROD')], ['C7 vs PROD', wins('C7', 'PROD')], ['D7 vs PROD', wins('D7', 'PROD')], ['A7@mast vs MAST', wins('A7@mast', 'MAST')], ['MAST vs PROD', wins('MAST', 'PROD')]]));
// by zoom step
const zr = [];
['PROD', 'MAST', 'A7', 'B7', 'C7', 'D7'].forEach(function (p) {
	if (!views[p] || !views[p].length) { return; }
	const r = [p];
	[0, 1, 2, 3, 4].forEach(function (k) { r.push(f(pooled(views[p].filter(function (v) { return v.step === k; })).labels)); });
	zr.push(r);
});
out.push('\n## Labels shown % by zoom (E1)\n');
out.push(table(['entrant', '1x', '1.5x', '2x', '3x', '4x'], zr));

// stability
const st = {};
['PROD', 'A7', 'B7', 'C7', 'D7'].forEach(function (p) { st[p] = lines(path.join(work, 'stabraw', p + '.jsonl')); });
if (st.PROD.length) {
	out.push('\n## Stability (stability.js): labels that change, per 100 labels shown in either view\n');
	out.push('32 sets (4 families, seeds 71-72, plain and bent-and-valved, 28 and 44 px), at 1x and 2x. "edit" pools the edit and its undo.\n\n');
	const srows = [];
	Object.keys(st).forEach(function (p) {
		const r = [p];
		['control', 'edit', 'pan'].forEach(function (kind) {
			const L = st[p].filter(function (x) { return kind === 'edit' ? (x.kind === 'edit' || x.kind === 'undo') : x.kind === kind; });
			const ch = L.reduce(function (t, x) { return t + x.changed; }, 0), se = L.reduce(function (t, x) { return t + x.shownEither; }, 0);
			const app = L.reduce(function (t, x) { return t + x.appeared + x.vanished; }, 0);
			const zero = L.filter(function (x) { return x.changed === 0; }).length;
			r.push(f(se ? 100 * ch / se : null, 2) + ' (' + f(L.length ? ch / L.length : null, 1) + ' per view; ' + f(se ? 100 * app / se : null, 2) + ' on/off; ' + zero + '/' + L.length + ' still)');
		});
		srows.push(r);
	});
	out.push(table(['entrant', 'control (same view again)', 'edit (one Z row one character wider)', 'pan (a tenth of the width)'], srows));
	const er = [];
	Object.keys(st).forEach(function (p) {
		[1, 2].forEach(function (m) {
			const r = [p + ' ' + m + 'x'];
			['control', 'edit', 'pan'].forEach(function (kind) {
				const L = st[p].filter(function (x) { return x.mult === m && (kind === 'edit' ? (x.kind === 'edit' || x.kind === 'undo') : x.kind === kind); });
				const ch = L.reduce(function (t, x) { return t + x.changed; }, 0), se = L.reduce(function (t, x) { return t + x.shownEither; }, 0);
				r.push(f(se ? 100 * ch / se : null, 2));
			});
			er.push(r);
		});
	});
	out.push('\nBy zoom:\n\n' + table(['entrant, zoom', 'control', 'edit', 'pan'], er));
}
process.stdout.write(out.join('\n'));
