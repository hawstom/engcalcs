<?php
/**
 * sw_map_host_selftest.php — assert that sw_map_host_check.php still sees a map host entering the
 * service worker, and still lets the ordinary manifest through. BLOCKING.
 *
 * WHY THIS EXISTS. The check finds nothing today and, if the rule holds, will find nothing
 * forever — which is exactly the state in which a working check and a broken one print the same
 * line. It has two specific ways to go blind that a fixture can pin: the manifest arrays are
 * parsed out of emitted TEXT, so a rename or a formatting change in `sw.php` silently leaves it
 * reading nothing (which is why "no array to read" is itself a finding in the check); and the host
 * denylist is a list of domains, so a sibling endpoint on the same service is the shape that gets
 * past a list written too tightly.
 *
 *   php dev/scripts/sw_map_host_selftest.php
 */

define('SW_MAP_HOST_LIB_ONLY', true);
require __DIR__ . '/sw_map_host_check.php';

/** A minimal worker skeleton with the two manifest arrays filled in. */
function ecSwFixture(array $assets, array $pages, string $extra = ''): string
{
    $j = static fn($a) => json_encode($a, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
    return "// EngCalcs Service Worker -- GENERATED BY sw.php\n"
        . "const ASSET_CACHE = 'engcalcs-assets';\n"
        . 'const STATIC_ASSETS = ' . $j($assets) . ";\n"
        . 'const CALC_PAGES = ' . $j($pages) . ";\n"
        . $extra;
}

$ok = ['/engcalcs/js/looped-network.js?v=1788062008', '/engcalcs/css/engcalcs.css?v=1788062008'];
$okPages = ['/engcalcs/Looped-Network.php', '/engcalcs/'];

$cases = [
    // ---- what it MUST find --------------------------------------------------------------------
    ['an OSM tile template precached -- the shape the rule is named for',
        ecSwFixture(array_merge($ok, ['https://tile.openstreetmap.org/{z}/{x}/{y}.png']), $okPages), true],
    ['a Mapbox Terrain-RGB URL, which is where a node coordinate would leak at install time',
        ecSwFixture($ok, $okPages, "self.addEventListener('fetch', e => fetch('https://api.mapbox.com/v4/mapbox.terrain-rgb/1/1/1.pngraw'));\n"), true],
    ['the Nominatim host in a runtime cache route -- not in the manifest at all, which is why the whole text is read',
        ecSwFixture($ok, $okPages, "// runtime-cache nominatim.openstreetmap.org lookups\n"), true],
    ['A SIBLING ENDPOINT ON THE SAME SERVICE. events.mapbox.com is not api.mapbox.com, and a denylist of exact hosts would miss it',
        ecSwFixture($ok, $okPages, "const TELEMETRY = 'https://events.mapbox.com/events/v2';\n"), true],
    ['a lettered OSM tile mirror, a.tile.openstreetmap.org',
        ecSwFixture(array_merge($ok, ['https://a.tile.openstreetmap.org/10/1/1.png']), $okPages), true],
    ['ANY cross-origin precache entry, map or not -- activate() deletes it on every load, so it can only ever be install cost',
        ecSwFixture(array_merge($ok, ['https://cdn.jsdelivr.net/npm/bootstrap/dist/bootstrap.min.css']), $okPages), true],
    ['a protocol-relative URL, which is cross-origin wearing a relative costume',
        ecSwFixture(array_merge($ok, ['//cdn.example.com/x.js']), $okPages), true],
    ['a same-origin path that is nonetheless a tile source of our own',
        ecSwFixture(array_merge($ok, ['/engcalcs/tiles/10/163/395.png']), $okPages), true],
    ['a relative entry, which resolves against scope and is a precache that half works',
        ecSwFixture(array_merge($ok, ['js/lpn-terrain.js?v=1']), $okPages), true],
    ['THE ARRAYS RENAMED AWAY. A check that reads text goes blind quietly; this fixture is what says so out loud',
        "const PRECACHE_URLS = [\n  \"/engcalcs/x.js\"\n];\n", true],

    // ---- what it must NOT report ---------------------------------------------------------------
    ['the ordinary manifest: same-origin absolute paths with filemtime query strings',
        ecSwFixture($ok, $okPages), false],
    ['a query string containing the letters z, x and y -- not a {z}/{x}/{y} template',
        ecSwFixture(array_merge($ok, ['/engcalcs/js/lpn-geom.js?v=1788062008&zxy=1']), $okPages), false],
    ['the word "tile" inside a FILENAME of ours, which is a module and not a tile',
        ecSwFixture(array_merge($ok, ['/engcalcs/js/lpn-tiles.js?v=1788062008']), $okPages), false],
    ["the real worker's own comment about deleting cross-origin entries, which names no host",
        ecSwFixture($ok, $okPages, "// anything cross-origin is pruned in activate (Task 287)\n"), false],
    ['the bare directory URL, which is a legitimate entry and nothing after the slash',
        ecSwFixture($ok, ['/engcalcs/']), false],
];

$fails = 0;
foreach ($cases as [$name, $sw, $wantFinding]) {
    $got = ecSwMapHostFindings($sw);
    $hit = $got !== [];
    if ($hit !== $wantFinding) {
        $fails++;
        echo "  FAIL $name\n";
        echo '        wanted ' . ($wantFinding ? 'a finding' : 'no finding') . ', got '
            . ($hit ? count($got) . ': ' . $got[0] : 'none') . "\n";
    } else {
        echo "  ok   $name\n";
    }
}

if ($fails) {
    echo "\n$fails fixture(s) failed. sw_map_host_check.php's reach has moved.\n";
    echo "A false negative here puts a third-party request inside the one file that runs before the\n";
    echo "visitor has asked for anything, and no page would show it happening.\n";
    exit(1);
}
echo "\nService-worker map-host selftest OK -- " . count($cases) . " fixtures, both directions.\n";
exit(0);
