<?php
/**
 * sw_scope_selftest.php -- assert sw_scope_check.php still sees each of the four ways the mount
 * list, the scope, the header and the routing can silently disagree. BLOCKING.
 *
 * Copyright 2009 Thomas Gail Haws
 * Licensed under GNU GPL v3.0 or later
 *
 * WHY THIS EXISTS. The check finds nothing today and, if the rule holds, finds nothing forever --
 * the state in which a working check and a blinded one print the same line. It reads emitted TEXT
 * in three of its four legs (a rendered page, the worker's own output, the worker's source), so
 * a rename or a reformat takes it blind with no failure. Each fixture below is one such blinding.
 *
 * THE DEFECT IT ULTIMATELY GUARDS HAS NO SYMPTOM AT ALL: a worker whose scope misses a mount
 * leaves that mount's visitors with no offline suite and no error anywhere. Nothing in this
 * repository or on that page would show it. So a false negative here is invisible twice over.
 *
 *   php dev/scripts/sw_scope_selftest.php
 */

define('SW_SCOPE_LIB_ONLY', true);
require __DIR__ . '/sw_scope_check.php';

$mounts = ['/engcalcs/' => 'the canonical mount', '/app/' => 'the LibreWaterNet mount'];

/** sw.php's source, as far as this check reads it. */
$srcOK  = "header('Content-Type: application/javascript; charset=utf-8');\n"
        . "header('Service-Worker-Allowed: ' . ecSwScope());\n";
$srcNone = "header('Content-Type: application/javascript; charset=utf-8');\n";
$srcLiteral = "header('Service-Worker-Allowed: /');\n";

/** The emitted worker, as far as this check reads it. */
function ecSwScopeWorker(array $routed, string $extra = "if (!inScope(url)) return;\n"): string
{
    return "// EngCalcs Service Worker -- GENERATED BY sw.php\n"
        . 'const APP_MOUNTS = ' . json_encode($routed, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT) . ";\n"
        . $extra;
}
$swOK = ecSwScopeWorker(['/engcalcs/', '/app/']);

/** A rendered page's registration block, as far as this check reads it. */
function ecSwScopePage(string $script, string $scopeExpr): string
{
    return "<script>\nif ('serviceWorker' in navigator) {\n"
        . "  navigator.serviceWorker.register('$script', { scope: $scopeExpr })\n}\n</script>\n";
}
$pageOK = ecSwScopePage('/engcalcs/sw.php', 'ecSwScope')
    . ecSwScopePage('/engcalcs/sw.php', '"/engcalcs/"');   // the narrow FALLBACK, legitimately present

$cases = [
    // ---- what it MUST find ---------------------------------------------------------------------
    ['THE DEFECT ITSELF: a mount the scope does not cover, which is silent in every browser',
        [$mounts, '/engcalcs/', $srcOK, $swOK, ecSwScopePage('/engcalcs/sw.php', '"/engcalcs/"'), '/engcalcs/'], true],
    ['the Service-Worker-Allowed header dropped -- which rejects EVERY registration, not just the new mount',
        [$mounts, '/', $srcNone, $swOK, $pageOK, '/engcalcs/'], true],
    ['THE HEADER HARDCODED. It passes today and is wrong the day a mount is added, which is this defect again',
        [$mounts, '/', $srcLiteral, $swOK, $pageOK, '/engcalcs/'], true],
    ['the page registering the narrow scope only, with the derived one never asked for',
        [$mounts, '/', $srcOK, $swOK, ecSwScopePage('/engcalcs/sw.php', '"/engcalcs/"'), '/engcalcs/'], true],
    ['A MOUNT CONTROLLED BUT NOT ROUTED -- the worker owns those pages and passes every request through, which looks identical from outside',
        [$mounts, '/', $srcOK, ecSwScopeWorker(['/engcalcs/']), $pageOK, '/engcalcs/'], true],
    ['a mount routed that nothing declares: a path somebody widened the worker over without saying why',
        [$mounts, '/', $srcOK, ecSwScopeWorker(['/engcalcs/', '/app/', '/beta/']), $pageOK, '/engcalcs/'], true],
    ['the inScope() gate gone, so a wide-scoped worker starts answering the parent site\'s requests',
        [$mounts, '/', $srcOK, ecSwScopeWorker(['/engcalcs/', '/app/'], "if (url.pathname.startsWith('/engcalcs/')) {}\n"), $pageOK, '/engcalcs/'], true],
    ['APP_MOUNTS RENAMED AWAY. A check that reads emitted text goes blind quietly; this is what says so',
        [$mounts, '/', $srcOK, "const MOUNT_PREFIXES = [\"/engcalcs/\"];\nif (!inScope(url)) return;\n", $pageOK, '/engcalcs/'], true],
    ['the registration block gone from the page entirely -- a bigger finding than a wrong scope',
        [$mounts, '/', $srcOK, $swOK, "<script>console.log('hi')</script>", '/engcalcs/'], true],
    ['a worker script served from outside the tree that generates the precache',
        [$mounts, '/', $srcOK, $swOK, ecSwScopePage('/sw.js', 'ecSwScope'), '/engcalcs/'], true],
    ['a mount written without its trailing slash, which makes startsWith() match /appendix too',
        [['/engcalcs/' => 'why', '/app' => 'why'], '/', $srcOK, ecSwScopeWorker(['/engcalcs/', '/app']), $pageOK, '/engcalcs/'], true],
    ['a mount declared with no reason: every mount widens a worker over pages that are not ours',
        [['/engcalcs/' => 'why', '/app/' => '  '], '/', $srcOK, $swOK, $pageOK, '/engcalcs/'], true],

    // ---- what it must NOT report ----------------------------------------------------------------
    ['the arrangement that actually ships: two mounts, scope /, header derived, both routed',
        [$mounts, '/', $srcOK, $swOK, $pageOK, '/engcalcs/'], false],
    ['THE NARROW FALLBACK REGISTRATION sitting beside the wide one. It is deliberate -- a host that strips the header must lose /app, not lose offline everywhere',
        [$mounts, '/', $srcOK, $swOK, $pageOK, '/engcalcs/'], false],
    ['ONE mount only, where the derived scope is the mount itself and no header widening is needed',
        [['/engcalcs/' => 'the only mount'], '/engcalcs/', $srcOK, ecSwScopeWorker(['/engcalcs/']), ecSwScopePage('/engcalcs/sw.php', 'ecSwScope'), '/engcalcs/'], false],
    ['the scope asked for as a literal rather than through the variable, which is the same ask',
        [$mounts, '/', $srcOK, $swOK, ecSwScopePage('/engcalcs/sw.php', '"/"'), '/engcalcs/'], false],
];

$fails = 0;
foreach ($cases as [$name, $args, $wantFinding]) {
    $got = ecSwScopeFindings(...$args);
    $hit = $got !== [];
    if ($hit !== $wantFinding) {
        $fails++;
        echo "  FAIL $name\n";
        echo '        wanted ' . ($wantFinding ? 'a finding' : 'no finding') . ', got '
            . ($hit ? count($got) . ': ' . $got[0] : 'none') . "\n";
    } else {
        echo "  ok   $name\n";
    }
}

if ($fails) {
    echo "\n$fails fixture(s) failed. sw_scope_check.php's reach has moved.\n";
    echo "The defect it guards -- a mount the worker cannot control -- produces no error in any\n";
    echo "browser and no symptom on the page. A false negative here is invisible twice over.\n";
    exit(1);
}
echo "\nService-worker scope selftest OK -- " . count($cases) . " fixtures, both directions.\n";
