/**
 * **THE TRANSLATORS' OWN QUESTIONS, IN THE SAME FILE AND UNDER THE SAME FLAG** (Tom, 2026-09-06:
 * *"16 English questions above: Put them in new-english-keys.md for my rulings."*).
 *
 * WHY IT BELONGS HERE. These are not new keys — they are SHIPPED, TRANSLATED strings that a wave-0
 * pass or a translator flagged as readable two ways, and `friction_check.php` refuses to launch a
 * sprint while any of them is unanswered. They therefore had exactly the problem this whole script
 * exists to fix: a list that lived in a script's output, which Tom never sees, while the one file
 * he does read said nothing about them. Two lists is one list somebody forgets.
 *
 * DERIVED, NEVER REMEMBERED. Read straight out of `dev/english-friction/*.json`; an entry appears
 * here iff its disposition is still open or referred, so answering one in the JSON removes it from
 * this file by itself and nobody has to delete anything.
 *
 * The ANSWER is harvested back into that entry's `disposition` and `resolution` by whoever reads
 * his marks, exactly as an approval is harvested into `dev/english-key-rulings.json`. The
 * hand-edit guard on `--write` protects both alike.
 */
function ecFrictionSection(string $root, int $langCount): string
{
    $dir = $root . '/dev/english-friction';
    if (!is_dir($dir)) { return ''; }
    $open = array();
    foreach (glob($dir . '/*.json') as $f) {
        $doc = json_decode((string)file_get_contents($f), true);
        if (!is_array($doc) || !isset($doc['entries']) || !is_array($doc['entries'])) { continue; }
        $sprint = isset($doc['sprint']) ? (string)$doc['sprint'] : basename($f, '.json');
        foreach ($doc['entries'] as $e) {
            if (!is_array($e) || !isset($e['key'])) { continue; }
            $d = isset($e['disposition']) ? (string)$e['disposition'] : 'open';
            if ($d !== 'open' && $d !== 'refer-to-human') { continue; }
            // **A QUESTION ABOUT A KEY THAT NO LONGER EXISTS IS NOT A QUESTION.** Tom was asked to
            // rule on `wi_save_and_calculate` on 2026-09-06 and answered *"Obsolete. There is no
            // such button. I have said this before. Remove the key."* -- and the key had already
            // been removed from all 27 files. The finding outlived the string it was about, which
            // is the friction log's own version of a stale claim. Dropped here rather than pruned
            // by hand, because the next one will happen the same way.
            if (ecLangValueOf($root, (string)$e['key']) === null) { continue; }
            $e['_sprint'] = $sprint;
            $open[] = $e;
        }
    }
    if (!$open) {
        return "\n## Questions from the translators  (0, all answered)\n\n"
            . "Nothing is waiting. Every English-friction finding has a disposition, so"
            . " `friction_check.php` is clear and a sprint can launch.\n";
    }
    usort($open, function ($a, $b) {
        return strcmp($a['_sprint'] . $a['key'], $b['_sprint'] . $b['key']);
    });
    $out = "\n## Questions from the translators  (" . count($open) . " to read " . EC_RULING_FLAG . ")\n\n"
        . "**These are SHIPPED strings, already translated into " . $langCount . " languages.** A wave-0\n"
        . "reading or a translator found each one readable two ways, and no sprint launches while one is\n"
        . "unanswered. You are not being asked to approve wording here; you are being asked which reading\n"
        . "is the one you meant. \"The first one\" is a complete answer.\n";
    $lastSprint = null;
    foreach ($open as $e) {
        if ($e['_sprint'] !== $lastSprint) {
            $lastSprint = $e['_sprint'];
            $out .= "\n### from sprint " . $lastSprint . "\n\n";
        }
        $out .= "- **`" . $e['key'] . "`**\n";
        $val = ecLangValueOf($root, (string)$e['key']);
        if ($val !== null) {
            $out .= "  > " . str_replace("\n", "\n  > ", $val) . "\n";
        }
        if (!empty($e['complaint'])) {
            $out .= "  *The finding:* " . trim((string)$e['complaint']) . "\n";
        }
        if (!empty($e['readings']) && is_array($e['readings'])) {
            foreach ($e['readings'] as $i => $r) {
                $out .= "  " . ($i + 1) . ". " . $r . "\n";
            }
        }
        $out .= ecAskLine($e);
        $out .= "  " . EC_RULING_FLAG . "\n";
    }
    return $out;
}

/**
 * **SAY WHAT KIND OF ANSWER THE QUESTION WANTS, BEFORE HE ANSWERS IT.**
 *
 * Tom, 2026-09-06, having read a whole batch: *"You added a batch of requests for me without
 * explaining what they were, and now after I am done I learn that they were proposed _syn entries.
 * Forgive me if I failed to read you right. Had I known earlier (had each entry said 'Add _syn key.
 * Suggestions follow'), it would have saved me a lot of confusion and time."*
 *
 * He read them all as wording approvals, because that is what the rest of the file is. Several were
 * not: they were requests for written permission to write a `$ec_lang_syn` entry, which is a
 * different decision with a different cost -- an approval is free and a syn entry is a standing
 * instruction to 26 translators. Two kinds of question under one flag is one kind of question
 * nobody answers correctly.
 *
 * **DERIVED FROM THE FINDING'S OWN `resolution`, never typed per entry.** The wave-0 pass already
 * states there what route it proposes, in a small vocabulary it uses consistently, so the label can
 * be read out of the record rather than maintained beside it. An entry whose resolution says
 * nothing recognisable gets the neutral line, which is the honest answer to "I cannot tell".
 */
function ecAskLine(array $e): string
{
    $r = isset($e['resolution']) ? (string) $e['resolution'] : '';
    $wantsSyn = (bool) preg_match('/\$ec_lang_syn/', $r);
    $wantsEnglish = (bool) preg_match('/PROPOSED English/i', $r);
    $wantsGloss = (bool) preg_match('/glossary\.json|glossary term/i', $r);
    $parts = array();
    if ($wantsEnglish) {
        $parts[] = 'a WORDING ruling -- is the English above right, or say what it should say';
    }
    if ($wantsSyn) {
        /* Named in full, because the standing rule is that AI never writes one without written
         * permission IN THE CONVERSATION, and "OK" on a line that does not say the words
         * `$ec_lang_syn` is not that permission. */
        $parts[] = 'WRITTEN PERMISSION to add a `$ec_lang_syn` entry for this key'
            . ' (a note to the 26 translators; it changes no English and nothing a visitor reads)';
    }
    if ($wantsGloss) {
        $parts[] = 'agreement to route the concept to `glossary.json`';
    }
    if (!$parts) {
        $parts[] = 'which of the readings above you meant';
    }
    $out = "  **What this asks for:** " . implode('; and ', $parts) . ".\n";
    /* The proposal itself, so a yes is answerable without opening another file. Trimmed, because a
     * resolution can be a paragraph and the ASK is the part that has to be readable at a glance. */
    if ($r !== '') {
        $one = trim(preg_replace('/\s+/', ' ', $r));
        if (strlen($one) > 400) { $one = substr($one, 0, 397) . '...'; }
        $out .= "  *The proposal:* " . $one . "\n";
    }
    return $out;
}

/** The current English for a key, or null. Read fresh so a finding can never quote a stale string. */
function ecLangValueOf(string $root, string $key): ?string
{
    static $lang = null;
    if ($lang === null) {
        $lang = array();
        $src = (string)file_get_contents($root . '/lib/lang.ec.en.php');
        if (preg_match_all("/\\\$ec_lang\\['([a-z0-9_]+)'\\]='((?:[^'\\\\]|\\\\.)*)';/", $src, $m, PREG_SET_ORDER)) {
            foreach ($m as $hit) {
                $lang[$hit[1]] = str_replace(array("\\'", '\\\\'), array("'", '\\'), $hit[2]);
            }
        }
    }
    return isset($lang[$key]) ? $lang[$key] : null;
}
