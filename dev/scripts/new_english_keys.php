/**
 * new_english_keys.php — English keys that exist in NO other language file.
 *
 * **WHY THIS EXISTS.** Tom asked, 2026-08-26: *"19 new keys are listed: Where?"* They were not.
 * Four batches of new English strings had been reported to him in conversation with the words
 * "listed in the task for your ruling", and exactly one batch had actually been written into
 * `dev/ROADMAP.md`. The other three existed only in an agent's report, which he never sees.
 *
 * A promise to paste a list is a promise somebody has to keep every time. **A key that is in
 * `lang.ec.en.php` and in none of the other 26 files is, by construction, a string nobody has
 * ruled on and no sprint has carried** — so the list can be derived instead of remembered, and
 * this script derives it.
 *
 * That is CLAUDE.md's own argument applied to my own failure: a rule a machine enforces is worth
 * roughly ten a human must remember.
 *
 * **AND THE LIST IS A FILE, NOT A COMMAND** (Tom, 2026-08-27): *"I don't have a list of strings to
 * review. I don't know what to do with the php file you gave me. Please give me a file."* Quite
 * right — a script he has to run is the same promise in a different costume. `dev/new-english-keys.md`
 * is generated by `--write`, tracked, and kept fresh by a BLOCKING `--check` in check_all.sh, which
 * is the only arrangement that cannot go stale between the day a key is written and the day he
 * reads it. It is the same treatment `dev/features.md` and `dev/roadmap-index.md` already get.
 *
 * Usage:
 *   php dev/scripts/new_english_keys.php            # grouped by prefix, with values
 *   php dev/scripts/new_english_keys.php --names    # names only, one per line
 *   php dev/scripts/new_english_keys.php --prefix=lpn_find
 *   php dev/scripts/new_english_keys.php --write    # (re)generate dev/new-english-keys.md
 *   php dev/scripts/new_english_keys.php --check    # is that file current? BLOCKING
 *
 * The console forms are ADVISORY and never exit non-zero: a new English key is the correct state
 * between writing a feature and translating it (CLAUDE.md — an ABSENT key is the correct
 * untranslated state), so the LIST is a worklist, never a verdict. Only `--check` can fail, and
 * what it fails on is the file being out of date, never the keys being there.
 */

$root = dirname(__DIR__, 2);
$argvAll = $argv;
$namesOnly = in_array('--names', $argvAll, true);
$write = in_array('--write', $argvAll, true);
$force = in_array('--force', $argvAll, true);
$check = in_array('--check', $argvAll, true);
$prefix = '';
foreach ($argvAll as $a) {
    if (strpos($a, '--prefix=') === 0) { $prefix = substr($a, 9); }
}

$ec_lang = array(); $ec_lang_syn = array();
require $root . '/lib/lang.ec.en.php';
$english = $ec_lang;

$others = glob($root . '/lib/lang.ec.*.php');
$seen = array();
$langCount = 0;
foreach ($others as $file) {
    if (basename($file) === 'lang.ec.en.php') { continue; }   // basename, not substr: 'ec.en.php' is nine characters and an off-by-one here silently counts English as one of the others, which makes the answer always zero.
    $ec_lang = array(); $ec_lang_syn = array();
    require $file;
    $langCount++;
    foreach (array_keys($ec_lang) as $k) { $seen[$k] = true; }
}

$new = array();
foreach ($english as $k => $v) {
    if (isset($seen[$k])) { continue; }
    if ($prefix !== '' && strpos($k, $prefix) !== 0) { continue; }
    $new[$k] = $v;
}
ksort($new);

/* THE FILE. One line per key: the name, then the English exactly as it is written, so a ruling can
 * be made from this page alone without opening lang.ec.en.php. Grouped by the FEATURE prefix rather
 * than listed flat, because the rulings come feature at a time and a flat list of 79 strings is a
 * list nobody starts. */
/**
 * **THE TOKEN TOM SEARCHES FOR.**
 *
 * `@@` because it cannot occur in an English string (measured: zero in `lang.ec.en.php`), cannot
 * occur in a key name, and — the part the first attempt got wrong — **carries no Markdown meaning**.
 * The first version used `>>>`, which merged into the `>` blockquote holding the string above it and
 * rendered as though "NEEDS RULING" were the last line of the string being ruled on.
 *
 * Written on every unruled key and on the heading of every group that still holds one, so the first
 * search lands on a section and the next walks its keys.
 */
const EC_RULING_FLAG = '@@ NEEDS RULING';

function newKeysMarkdown($new, $total, $langCount) {
    $root = dirname(__DIR__, 2);
    $out = "# English strings nobody has ruled on yet

";
    $out .= "**Generated — never hand-edited.** `php dev/scripts/new_english_keys.php --write`.
";
    $out .= "`check_all.sh` fails if this file has drifted from `lib/lang.ec.en.php`.

";
    $out .= "These are the keys that are in `lib/lang.ec.en.php` and in NONE of the other "
        . $langCount . " language
files — which is, by construction, every string that has been written and not yet ruled on or
"
        . "translated. **An absent key is the correct untranslated state**, so this is a worklist and never
"
        . "a fault.

";
    $out .= "What to do with it: read the English, and say where it is wrong. A ruling is a sentence in
"
        . "conversation, not an edit — the wording is Tom's and the editing is AI's. Once the wording is
"
        . "settled these go into the next translation sprint as a batch.

";
    // **THE NUMBER THAT MATTERS IS THE UNRULED ONE.** A count of the whole list tells a reader
    // nothing about the size of the job in front of them; 103 keys of which 92 are already approved
    // is eleven minutes, not an afternoon, and saying so is the difference between a list somebody
    // opens and one they put off.
    $unruled = 0;
    foreach ($new as $nk => $nv) { if (ecRulingLine($nk, $nv) === '') { $unruled++; } }
    $out .= "**" . $unruled . " still to read on master**, of " . count($new) . " untranslated keys, of "
        . $total . " English keys. **A branch section follows if anything is waiting there.** A key already marked _Ruled OK_ below needs nothing from you;\n"
        . "the ruling lapses by itself if the wording changes.

"
        /* **A LIST YOU CANNOT NAVIGATE IS A LIST THAT DOES NOT GET READ.** Tom, 2026-09-01: *"I
         * can't easily find where I am needed in dev/new-english-keys.md. You must put a searchable
         * flag there for me to use in my text editor to jump to where I am needed."* The token is
         * on every unruled key AND on the heading of every group that still has one, so the first
         * search lands on a section and the next walks the keys in it. It is deliberately a string
         * no English sentence and no key name can contain, so a search never lands on prose. */
        . "**Search for `" . EC_RULING_FLAG . "` to jump to every key that still needs you.** It sits\n"
        . "under each unread key, and on the heading of each group that still has one — so the first\n"
        . "hit takes you to a section and the rest walk its keys. A key already ruled does not carry\n"
        . "it, and a fully ruled group says `all ruled` and can be skipped whole.\n"
        . "Write your answer on the flag's own line. Anything is fine; \"OK\" is enough.
";
    $out .= ecFrictionSection($root, $langCount);
    if (!$new) {
        return $out . "
None on master. Every English key here is present in at least one other language.
"
            . ecBranchSection($root, $GLOBALS['english']);
    }
    $groups = array();
    foreach ($new as $k => $v) {
        $p = (strpos($k, '_') !== false) ? substr($k, 0, strpos($k, '_')) : $k;
        $groups[$p][$k] = $v;
    }
    ksort($groups);
    foreach ($groups as $p => $keys) {
        $groupUnruled = 0;
        foreach ($keys as $gk => $gv) { if (ecRulingLine($gk, $gv) === '') { $groupUnruled++; } }
        /* **THE HEADING CARRIES THE FLAG TOO WHEN THE GROUP HAS WORK IN IT**, so a search for the
         * token lands on the section before it lands on the first key inside it. A group that is
         * fully ruled says so and can be skipped whole. */
        $out .= "
## " . $p . "_  (" . count($keys) . ($groupUnruled > 0
            ? ", " . $groupUnruled . " to read " . EC_RULING_FLAG
            : ", all ruled") . ")

";
        foreach ($keys as $k => $v) {
            /* The value verbatim, in a fenced quote rather than a table cell: several of these are
             * whole paragraphs with commas and pipes in them, and a table would eat both. */
            $ruled = ecRulingLine($k, $v);
            $out .= "- **`" . $k . "`**
  > " . str_replace("
", "
  > ", $v) . "
" . ($ruled !== '' ? $ruled : "  " . EC_RULING_FLAG . "
");
        }
    }
    return $out . ecBranchSection($root, $GLOBALS['english']);
}

/**
 * **HIS READING LIST WAS BLIND TO EVERY BRANCH, WHICH IS NOW WHERE THE WORK LIVES.**
 *
 * Tom, 2026-09-17: *"dev/new-english-keys.md is empty. Please check."* It was, and it was CORRECT:
 * the derivation above compares the English file against the other 26 IN THE CHECKED-OUT TREE, and
 * on master there were genuinely no new keys. The 24 strings awaiting him were on two unmerged
 * feature branches.
 *
 * **THAT USED TO BE FINE AND STOPPED BEING FINE ON 2026-09-12.** Under the old paradigm new strings
 * landed on master and appeared here. Under branch work a FEATURE waits on its branch until he has
 * used it and said so -- so the list went structurally blind to exactly the work that is waiting for
 * him, which is the opposite of what it is for. His reading is the critical path; a reading list
 * that cannot see the unread work is worse than none, because it reports zero and reads as done.
 *
 * **IT IS ADVISORY AND IT IS DELIBERATELY OUTSIDE `--check`.** A branch tip moves whenever anybody
 * commits on it, so blocking on this section would fail master's build for work happening somewhere
 * else entirely -- a gate that fires on somebody else's commit is a gate that gets switched off.
 * `--check` still blocks on the master-derived part exactly as before; this section carries each
 * branch's SHA so a reader can see for themselves whether it is current, and `--check` PRINTS a
 * note when it has drifted without failing.
 *
 * A branch with no new English keys is named and dismissed in one line, because "this branch adds
 * none" is a real answer and silence is not.
 */
function ecBranchNewKeys(string $root): array {
    $out = array();
    $branches = array();
    exec('cd ' . escapeshellarg($root) . ' && git branch --no-merged master --format="%(refname:short)" 2>/dev/null', $branches);
    foreach ($branches as $b) {
        $b = trim($b);
        if ($b === '' || $b === 'master') { continue; }
        $sha = array();
        exec('cd ' . escapeshellarg($root) . ' && git rev-parse --short ' . escapeshellarg($b) . ' 2>/dev/null', $sha);
        $src = array();
        $rc = 0;
        exec('cd ' . escapeshellarg($root) . ' && git show ' . escapeshellarg($b . ':lib/lang.ec.en.php') . ' 2>/dev/null', $src, $rc);
        if ($rc !== 0 || !$src) { continue; }
        // The branch's English file is PARSED, never required: requiring it would run another
        // commit's PHP in this process and let the later file win in $ec_lang. A token scan cannot
        // do that, and a single-quoted assignment is the only form rule D allows anyway.
        $keys = array();
        foreach ($src as $line) {
            if (preg_match("/^\\\$ec_lang\\['([A-Za-z0-9_]+)'\\]\\s*=\\s*'(.*)';\\s*$/", $line, $m)) {
                $keys[$m[1]] = str_replace(array("\\'", "\\\\"), array("'", "\\"), $m[2]);
            }
        }
        // **A KEY MASTER DELETED AFTER THE BRANCH WAS CUT IS NOT NEW** (2026-09-25). A branch far
        // behind master still carries every key master has since removed, and listing those asked
        // Tom to rule on some twenty strings that no longer exist anywhere he could see them. A key
        // present at the merge base is the branch's inheritance, not its authorship, so it is
        // dropped here; the merge will remove it.
        $base = array();
        exec('cd ' . escapeshellarg($root) . ' && git merge-base HEAD ' . escapeshellarg($b) . ' 2>/dev/null', $base);
        if (isset($base[0]) && $base[0] !== '') {
            $bsrc = array();
            exec('cd ' . escapeshellarg($root) . ' && git show ' . escapeshellarg(trim($base[0]) . ':lib/lang.ec.en.php') . ' 2>/dev/null', $bsrc);
            foreach ($bsrc as $line) {
                if (preg_match('/^\$ec_lang\[\'([A-Za-z0-9_]+)\'\]\s*=/', $line, $m) && isset($keys[$m[1]])) {
                    unset($keys[$m[1]]);
                }
            }
        }
        $out[$b] = array('sha' => isset($sha[0]) ? $sha[0] : '?', 'keys' => $keys);
    }
    ksort($out);
    return $out;
}

function ecBranchSection(string $root, array $masterEnglish): string {
    $branches = ecBranchNewKeys($root);
    if (!$branches) { return ''; }

    $body = '';
    $totalUnruled = 0;
    $totalNew = 0;
    foreach ($branches as $b => $info) {
        $added = array();
        foreach ($info['keys'] as $k => $v) {
            if (!array_key_exists($k, $masterEnglish)) { $added[$k] = $v; }
        }
        ksort($added);
        if (!$added) {
            $body .= "\n### " . $b . " (`" . $info['sha'] . "`) — adds no English strings\n";
            continue;
        }
        $unruled = 0;
        foreach ($added as $k => $v) { if (ecRulingLine($k, $v) === '') { $unruled++; } }
        $totalUnruled += $unruled;
        $totalNew += count($added);
        $body .= "\n### " . $b . " (`" . $info['sha'] . "`) — " . count($added) . " new, "
            . ($unruled > 0 ? $unruled . " to read " . EC_RULING_FLAG : "all ruled") . "\n\n";
        foreach ($added as $k => $v) {
            $ruled = ecRulingLine($k, $v);
            $body .= "- **`" . $k . "`**\n  > " . str_replace("\n", "\n  > ", $v) . "\n"
                . ($ruled !== '' ? $ruled : "  " . EC_RULING_FLAG . "\n");
        }
    }

    $head = "\n---\n\n# Strings waiting on a branch\n\n"
        . "**" . $totalUnruled . " still to read**, of " . $totalNew . " new keys across "
        . count($branches) . " unmerged branch(es).\n\n"
        . "A feature waits on its branch until you have used it and said so, so this is where new\n"
        . "wording lives before it reaches master. **These strings are real and are not on master**,\n"
        . "which is why the list above can honestly say none while there is reading to do here.\n\n"
        . "Each branch carries the commit it was read at. This part is a SNAPSHOT and is not held\n"
        . "fresh by the build — a branch moves whenever anybody commits on it, and failing master's\n"
        . "build for that would be a gate nobody keeps. Refresh it with\n"
        . "`php dev/scripts/new_english_keys.php --write`.\n";

    return $head . $body;
}

/**
 * **A RULING IS REMEMBERED, AND IT IS REMEMBERED AGAINST THE EXACT ENGLISH IT WAS MADE ON.**
 *
 * WHY. Tom read this whole list on 2026-08-28 and marked every key `OK.` or `Edited.` — 92 of them.
 * The `Edited.` ones went into `lang.ec.en.php` and are safe. **The 81 `OK.`s were about to be
 * thrown away by the next regeneration**, which would have handed him the same 101 keys unmarked
 * and asked him to read the ones he had just approved. That is precisely the waste he was
 * complaining about when he said *"I painstakingly edited it again."*
 *
 * So an approval is data now, in `dev/english-key-rulings.json`, and this line is how it comes back.
 *
 * **KEYED ON THE TEXT, NOT ON THE KEY NAME.** A ruling means "these words are right", so it lapses
 * the moment the words change: reword a string and it reappears unruled, which is correct — nobody
 * approved the new sentence. That is also what stops the file from silently going quiet as strings
 * drift underneath their approvals.
 */
function ecRulingLine(string $key, string $value): string
{
    static $rulings = null;
    if ($rulings === null) {
        $f = dirname(__DIR__) . '/english-key-rulings.json';
        $j = is_file($f) ? json_decode(file_get_contents($f), true) : null;
        $rulings = (is_array($j) && isset($j['rulings']) && is_array($j['rulings'])) ? $j['rulings'] : array();
    }
    if (!isset($rulings[$key]) || !is_array($rulings[$key])) { return ''; }
    $r = $rulings[$key];
    if (!isset($r['on']) || $r['on'] !== $value) { return ''; }
    /* **HIS OWN WORDS COME BACK, NOT A BOOLEAN.** `harvest_english_rulings.php` stores the mark
     * verbatim, because "OK." and "It's fine as is. Add a _syn per 1." are both readings and only
     * one of them is finished. Printing it back is also the receipt: he can see on the page that
     * what he wrote was kept, which is the whole of the complaint that produced the harvester. */
    $date = isset($r['ruled']) ? $r['ruled'] : '';
    $answer = isset($r['answer']) ? trim((string) $r['answer']) : '';
    /* **AND A QUESTION HE ASKED GETS ITS ANSWER BACK ON THE SAME LINE.** Several of his marks are
     * questions -- "isn't this impossible?", "where is this used?" -- and an answer given only in a
     * session report is an answer he never sees, which is the same failure as a ruling stored only
     * in a session report. `reply` is written by whoever answers it and printed here, so the loop
     * closes in the one file he actually opens. */
    $reply = isset($r['reply']) ? trim((string) $r['reply']) : '';
    $out = '';
    if ($answer !== '' && !preg_match('/^(ok|ok\.|okay|okay\.|edited|edited\.|fine|fine\.)$/i', $answer)) {
        $out = "  _Ruled " . $date . ": " . str_replace("\n", ' ', $answer) . "_\n";
    } else {
        $out = "  _Ruled OK " . $date . "._\n";
    }
    if ($reply !== '') { $out .= "  _Answer: " . str_replace("\n", ' ', $reply) . "_\n"; }
    return $out;
}

// **LEAD WITH THE NUMBER THAT NEEDS A HUMAN, NOT THE ONE THAT NEEDS A SPRINT.** These two counts
// are different questions and reading one as the other has now cost a session: "79 keys awaiting a
// ruling" was printed on a tree where 78 were already ruled and ONE was outstanding, and it was
// reported to Tom as 79 keys awaiting his reading. His answer: *"You say 79. But there is one."*
// The untranslated count is a sprint's size; the unruled count is what a person still owes.
$ecUnruled = 0;
foreach ($new as $k => $v) { if (ecRulingLine($k, $v) === '') { $ecUnruled++; } }
/* **THE HEADLINE COUNTS BRANCHES TOO, OR IT REPORTS ZERO WHILE THERE IS READING TO DO.** On
 * 2026-09-17 this line said "0 still to read" while 120 new strings sat on seven unmerged branches,
 * and Tom read the zero and asked what was wrong with the file. Nothing was: the number was true
 * about master and useless as an answer to "is there anything for me?". */
$ecBranchWaiting = 0;
foreach (ecBranchNewKeys($root) as $bInfo) {
    foreach ($bInfo['keys'] as $bk => $bv) {
        if (array_key_exists($bk, $english)) { continue; }
        if (ecRulingLine($bk, $bv) === '') { $ecBranchWaiting++; }
    }
}
$ecCounts = $ecUnruled . ' still to read on master, ' . count($new) . ' untranslated'
    . ($ecBranchWaiting > 0 ? '; ' . $ecBranchWaiting . ' more waiting on branches' : '');

if ($write || $check) {
    $file = $root . '/dev/new-english-keys.md';
    $want = newKeysMarkdown($new, count($english), $langCount);
    $have = is_file($file) ? file_get_contents($file) : '';
    if ($check) {
        /* **THE BRANCH SECTION IS COMPARED BUT NEVER BLOCKS, AND THAT SPLIT IS THE WHOLE DESIGN.**
         * A branch tip moves whenever anybody commits on it, so blocking on that half would fail
         * MASTER's build because of work happening somewhere else -- and a gate that fires on
         * somebody else's commit is a gate somebody switches off, which is this project's own rule.
         * So the master-derived half keeps the guarantee it has always had, and the branch half is
         * reported as a note. Split on the section's own heading, which no key name or English
         * string can contain. */
        $cut = function ($text) {
            $i = strpos($text, "\n---\n\n# Strings waiting on a branch");
            return $i === false ? array($text, '') : array(substr($text, 0, $i), substr($text, $i));
        };
        list($wantMain, $wantBranch) = $cut($want);
        list($haveMain, $haveBranch) = $cut($have);
        if ($wantMain === $haveMain) {
            echo "FRESH (" . $ecCounts . ")\n";
            if ($wantBranch !== $haveBranch) {
                echo "  note: the branch section has drifted (a branch moved). Advisory, never blocking.\n"
                   . "        Refresh it with:  php dev/scripts/new_english_keys.php --write\n";
            }
            exit(0);
        }
        fwrite(STDERR, "STALE: dev/new-english-keys.md does not match lib/lang.ec.en.php.\n\n");
        fwrite(STDERR, "    Regenerate it:  php dev/scripts/new_english_keys.php --write\n\n");
        fwrite(STDERR, "This file is generated, never hand-edited. It is the list Tom reads; a stale one is\n");
        fwrite(STDERR, "the exact failure this script was written for.\n");
        exit(1);
    }
    /*
     * **--write REFUSES TO CLOBBER A FILE SOMEBODY HAS EDITED BY HAND** (2026-08-28).
     *
     * WHY, AND IT IS A REAL LOSS, NOT A HYPOTHETICAL. Tom, of this very file: *"545: I did this
     * task. I believe you overwrote my painstaking edits. Can you restore them?"* They were not
     * recoverable — not in any commit, not in a dangling blob, not in a stash. The file is
     * generated, its header says so, and the process is that a ruling is a sentence in
     * conversation; none of that stops a person from doing the obvious thing, which is to read the
     * list in the file and mark it up in the file.
     *
     * **AND THE REGENERATION IS THE EASIEST COMMAND IN THIS REPO TO RUN INNOCENTLY.** Any session
     * that adds one English key runs it. So the danger is not carelessness, it is that the safe
     * routine and the destructive one are the same keystroke.
     *
     * **THE TEST IS "WAS THE FILE EDITED", NOT "HAS IT DRIFTED".** Drift is the NORMAL state: any
     * session that adds one English key leaves this file stale, and refusing there would fire on
     * every ordinary run and teach everyone to pass --force. So it compares what is ON DISK with
     * what git last COMMITTED. Equal means nobody has touched the file and the difference from
     * `$want` is entirely somebody editing `lang.ec.en.php` — regenerate freely. Unequal means a
     * human has been in here, and that is the case worth stopping for.
     *
     * Outside a git checkout it cannot tell, and it writes rather than blocking work it cannot
     * reason about. check_all.sh always runs in one.
     */
    $committed = null;
    $rc = 1;
    $outLines = array();
    @exec('git -C ' . escapeshellarg($root) . ' show HEAD:dev/new-english-keys.md 2>/dev/null', $outLines, $rc);
    if ($rc === 0) { $committed = implode("\n", $outLines) . "\n"; }
    /*
     * **COMPARE LINE BY LINE WITH TRAILING SPACE STRIPPED, because exec() ALREADY DID THAT to one
     * side and not the other.** PHP's exec() trims trailing whitespace from every line it returns,
     * so a committed file holding ONE line that ends in a space can never equal what is on disk --
     * and this guard then reports 'hand edited' for ever, on a file nobody has touched. It is not
     * hypothetical: Tom's 2026-09-01 rulings included the line `..."No. of passes" or "No. of runs" `
     * and that single space made the list unregenerable, which is the one thing this script exists
     * to make routine. A human writing on this file is EXACTLY the case that leaves trailing
     * spaces, so the false positive fires precisely when the guard matters most.
     *
     * Normalising both sides the same way keeps the guard's real question -- has a human written
     * anything here -- and drops the one difference that is an artefact of how we read the file.
     */
    $normalise = function ($text) {
        $lines = preg_split('/\r\n|\n|\r/', (string) $text);
        foreach ($lines as $i => $line) { $lines[$i] = rtrim($line); }
        return rtrim(implode("\n", $lines));
    };
    $handEdited = ($committed !== null && $have !== '' && $normalise($have) !== $normalise($committed));
    if ($handEdited && !$force) {
        fwrite(STDERR, "REFUSING TO WRITE: dev/new-english-keys.md has been edited since it was\n");
        fwrite(STDERR, "last generated, and regenerating would discard those edits permanently.\n\n");
        fwrite(STDERR, "This has already happened once, to Tom, and the edits were not recoverable\n");
        fwrite(STDERR, "from git — the file is only ever committed in its generated form.\n\n");
        fwrite(STDERR, "    See what changed:   git diff dev/new-english-keys.md\n");
        fwrite(STDERR, "    Keep the edits:     read them, apply the wording to lib/lang.ec.en.php,\n");
        fwrite(STDERR, "                        then regenerate — the file will match again by itself\n");
        fwrite(STDERR, "    Discard them:       php dev/scripts/new_english_keys.php --write --force\n\n");
        fwrite(STDERR, "Do not reach for --force to get past this. The whole point of the file is that\n");
        fwrite(STDERR, "somebody reads it, and somebody reading it will write on it.\n");
        exit(2);
    }
    // **--force IS NEVER SILENT ANY MORE, AND THAT IS THE HALF THAT WAS MISSING.**
    //
    // The refusal above is a good guard against a person typing --force. It is a POOR guard against
    // a script, and on 2026-09-02 the orchestrating AI wrote
    // `... --write || ... --write --force` -- a fallback that reaches for --force EXACTLY when the
    // guard fires, which is exactly when a human has written on the file. It discarded nothing that
    // day, as far as anyone can tell, and nobody could tell, which is the problem.
    //
    // So a forced write now PRINTS what it is discarding, line by line, to stdout. It cannot be
    // redirected away by a caller that only silenced stderr, and a reader of the run log can
    // recover the marks by hand. Cheap, and it turns an unrecoverable loss into a noisy one.
    if ($handEdited && $force) {
        // **THE WHOLE HAND-EDITED FILE IS SAVED BEFORE IT IS OVERWRITTEN. PRINTING IS NOT ENOUGH.**
        //
        // The first version of this only printed the discarded lines, on the argument that a noisy
        // loss beats a silent one. It was proved insufficient within the hour, by me: I ran a forced
        // write to DEMONSTRATE the printing, on a live file Tom had just written on, piped the
        // output through `head -8`, and destroyed the rest of his marks with the evidence scrolling
        // past. Three approvals and about six other lines were gone, and the printout I had kept
        // held one of them.
        //
        // So the copy is a FILE now. `--force` is survivable rather than merely loud, and the
        // recovery does not depend on anybody having kept a terminal buffer.
        $rej = dirname($file) . '/new-english-keys.rejected.md';
        file_put_contents($rej, $have);
        $a = explode("\n", $normalise($committed));
        $b = explode("\n", $normalise($have));
        $lost = array_values(array_diff($b, $a));
        echo "--force: DISCARDING " . count($lost) . " hand-edited line(s) from dev/new-english-keys.md.\n";
        echo "The WHOLE hand-edited file has been copied to:\n";
        echo "    " . $rej . "\n";
        echo "Nothing is lost. The discarded lines were:\n\n";
        foreach ($lost as $line) { echo '    ' . $line . "\n"; }
        echo "\nIf any of that is a ruling, put it in dev/english-key-rulings.json or in\n";
        echo "lib/lang.ec.en.php, then delete the .rejected.md copy.\n\n";
    }
    file_put_contents($file, $want);
    echo "dev/new-english-keys.md written — " . $ecCounts . "\n";
    exit(0);
}

if ($namesOnly) {
    foreach (array_keys($new) as $k) { echo $k, "\n"; }
